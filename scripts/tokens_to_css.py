#!/usr/bin/env python3
"""Build templates/tokens.css and templates/tailwind-theme.css from tokens.json + tokens.dark.json (DES-35, STK-07).
With --check, exit 1 if either file is stale or a var() is undefined."""
import json, re, sys

REF = re.compile(r"\{([^}]+)\}")

def flatten(node, path=(), out=None):
    out = {} if out is None else out
    if isinstance(node, dict) and "$value" in node:
        out[".".join(path)] = node
    elif isinstance(node, dict):
        for k, v in node.items():
            if not k.startswith("$"):
                flatten(v, path + (k,), out)
    return out

def var(path):
    return "var(--" + path.replace(".", "-") + ")"

def css(v, t):
    # References stay var() so a theme only has to redefine semantic properties.
    if isinstance(v, str) and REF.fullmatch(v):
        return var(REF.fullmatch(v).group(1))
    if t == "color":
        if "alpha" in v:
            r, g, b = (round(c * 255) for c in v["components"])
            return f"rgb({r} {g} {b} / {v['alpha']})"
        return v["hex"]
    if t in ("dimension", "duration"):
        return f"{v['value']}{v['unit']}"
    if t == "cubicBezier":
        return "cubic-bezier(" + ", ".join(str(x) for x in v) + ")"
    if t == "fontFamily":
        return ", ".join(f'"{f}"' if " " in f else f for f in v)
    if t in ("number", "fontWeight", "strokeStyle"):
        return str(v)
    if t == "shadow":
        s = " ".join(css(v[k], "dimension") for k in ("offsetX", "offsetY", "blur", "spread")) + " " + css(v["color"], "color")
        return ("inset " if v.get("inset") else "") + s
    if t == "border":
        return f"{css(v['width'], 'dimension')} {css(v['style'], 'strokeStyle')} {css(v['color'], 'color')}"
    if t == "transition":
        return f"{css(v['duration'], 'duration')} {css(v['timingFunction'], 'cubicBezier')} {css(v['delay'], 'duration')}"
    if t == "gradient":
        return "linear-gradient(" + ", ".join(f"{css(s['color'], 'color')} {round(s['position'] * 100)}%" for s in v) + ")"
    if t == "typography":
        return f"{css(v['fontWeight'], 'fontWeight')} {css(v['fontSize'], 'dimension')}/{css(v['lineHeight'], 'number')} {css(v['fontFamily'], 'fontFamily')}"
    raise ValueError(f"unknown type {t}")

def block(tokens, pad="  "):
    lines = []
    for path, tok in tokens.items():
        name, v = path.replace(".", "-"), tok["$value"]
        lines.append(f"{pad}--{name}: {css(v, tok['$type'])};")
        if tok["$type"] == "typography":  # `font` shorthand can't carry letter-spacing
            ls = var(REF.fullmatch(v).group(1))[:-1] + "-letter-spacing)" if isinstance(v, str) else css(v["letterSpacing"], "dimension")
            lines.append(f"{pad}--{name}-letter-spacing: {ls};")
    return "\n".join(lines)

base = flatten(json.load(open("templates/tokens.json", encoding="utf-8")))
dark = flatten(json.load(open("templates/tokens.dark.json", encoding="utf-8")))
out = (
    "/* Generated by scripts/tokens_to_css.py from tokens.json and tokens.dark.json. Do not edit by hand. */\n\n"
    f":root {{\n{block(base)}\n}}\n\n"
    f"@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{\n{block(dark, '    ')}\n  }}\n}}\n\n"
    f":root[data-theme=\"dark\"] {{\n{block(dark)}\n}}\n"
)

defined = set(re.findall(r"^\s*(--[\w-]+):", out, re.M))
undefined = sorted(set(re.findall(r"var\((--[\w-]+)\)", out)) - defined)
assert not undefined, f"undefined custom properties: {undefined}"
assert "--primitive-duration-fast" in defined and "--semantic-elevation-dropdown" in defined  # names motion.css relies on

def tailwind(tokens):
    # Token-only Tailwind v4 theme: reset every default, then expose tokens. `inline` keeps var() so dark mode still switches.
    rows = ["  --*: initial;"]
    def add(name, path):
        rows.append(f"  --{name}: {var(path)};")
    for path in tokens:
        p = path.split(".")
        if p[:2] == ["semantic", "color"]:
            add("color-" + "-".join(p[2:]), path)
        elif p[:2] == ["primitive", "space"]:
            add("spacing-" + p[2], path)
        elif p[:2] == ["primitive", "radius"]:
            add("radius-" + p[2], path)
        elif p[:2] == ["semantic", "text"]:
            add("text-" + p[2], path)
        elif p[:3] == ["primitive", "font", "family"]:
            add("font-" + p[3], path)
        elif p[:3] == ["primitive", "font", "weight"]:
            add("font-weight-" + p[3], path)
        elif p[:3] == ["primitive", "font", "lineHeight"]:
            add("leading-" + p[3], path)
        elif p[:3] == ["primitive", "font", "letterSpacing"]:
            add("tracking-" + p[3], path)
        elif p[:2] == ["semantic", "elevation"]:
            add("shadow-" + p[2], path)
        elif p[:2] == ["primitive", "easing"]:
            add("ease-" + p[2], path)
        elif p[:2] == ["primitive", "blur"]:
            add("blur-" + p[2], path)
        elif p[:2] == ["primitive", "aspectRatio"]:
            add("aspect-" + p[2], path)
        elif p[:2] == ["primitive", "breakpoint"]:
            # Media queries can't read var(): literal em values, so breakpoints follow the user's font size (LAY-01).
            rows.append(f"  --breakpoint-{p[2]}: {tokens[path]['$value']['value'] / 16:g}em;")
    return "/* Generated by scripts/tokens_to_css.py --tailwind. Load after tokens.css. Do not edit by hand. */\n\n@theme inline {\n" + "\n".join(rows) + "\n}\n"

tw = tailwind(base)
tw_vars = set(re.findall(r"var\((--[\w-]+)\)", tw))
assert not tw_vars - defined, f"tailwind theme references undefined: {sorted(tw_vars - defined)}"
assert "--color-action-primary" in tw and "--spacing-4" in tw and "--breakpoint-tablet: 37.5em" in tw

if "--check" in sys.argv:
    stale = []
    for name, content in (("templates/tokens.css", out), ("templates/tailwind-theme.css", tw)):
        try:
            if open(name, encoding="utf-8").read() != content:
                stale.append(name)
        except FileNotFoundError:
            stale.append(name)
    if stale:
        print("stale: " + ", ".join(stale) + ": run scripts/tokens_to_css.py")
        sys.exit(1)
else:
    open("templates/tokens.css", "w", encoding="utf-8").write(out)
    open("templates/tailwind-theme.css", "w", encoding="utf-8").write(tw)
